// The shapes of Forgejo's answers are generated by OpenAPI Generator from Codeberg's own API description,
// spec/forgejo.swagger.json (refreshed by tools/specs/fetch.py), into the `api` package: models only, the calls stay
// ForgejoHttp's. Gitea's description (spec/gitea.swagger.json) is kept beside it to compare when Gitea moves apart.
val preparedSpec = layout.buildDirectory.file("spec/forgejo.json")

// Forgejo names closed lists of values (a merge style, a review state...) that grow with each release: generated as
// Kotlin enums, a value a newer server adds would make its whole answer unreadable. They are read as plain strings.
val prepareSpec by tasks.registering {
    // Only plain values are taken into the action, never the script's own: the configuration cache can't keep those.
    val source = layout.projectDirectory.file("spec/forgejo.swagger.json")
    val target = preparedSpec
    inputs.file(source)
    outputs.file(target)
    doLast {
        val tree = JsonSlurper().parse(source.asFile) as Map<*, *>
        fun dropEnums(node: Any?) {
            when (node) {
                is MutableMap<*, *> -> {
                    node.remove("enum")
                    node.values.forEach(::dropEnums)
                }
                is List<*> -> node.forEach(::dropEnums)
            }
        }
        dropEnums(tree["definitions"])
        target.get().asFile.apply { parentFile.mkdirs() }.writeText(JsonOutput.toJson(tree))
    }
}

val generatedApi = layout.buildDirectory.dir("generated/openapi")

tasks.named<GenerateTask>("openApiGenerate") {
    dependsOn(prepareSpec)
    generatorName.set("kotlin")
    inputSpec.set(preparedSpec)
    outputDir.set(generatedApi)
    packageName.set("fr.arthurbrugiere.forgeline.forge.forgejo.api")
    modelPackage.set("fr.arthurbrugiere.forgeline.forge.forgejo.api")
    globalProperties.set(mapOf("models" to "", "modelDocs" to "false", "modelTests" to "false"))
    // Free-form JSON stays JSON.
    typeMappings.set(mapOf("AnyType" to "JsonElement", "object" to "JsonElement"))
    importMappings.set(mapOf("JsonElement" to "kotlinx.serialization.json.JsonElement"))
    configOptions.set(
        mapOf(
            "library" to "jvm-ktor",
            "serializationLibrary" to "kotlinx_serialization",
            "dateLibrary" to "string",
            "modelMutable" to "false",
            "sourceFolder" to "src/main/kotlin",
        ),
    )
}

kotlin.sourceSets.named("main") { kotlin.srcDir(generatedApi.map { it.dir("src/main/kotlin") }) }

tasks.named("compileKotlin") { dependsOn("openApiGenerate") }

// Contract tests against the real Codeberg, run nightly by .github/workflows/live.yml. They pin what
// docs/CODEBERG.md relies on. Most run without an account; the signed-in ones only read, need
// CODEBERG_LIVE_TOKEN and are skipped without it.
testing {
    suites {
        register<JvmTestSuite>("liveTest") {
            useJUnit(libs.versions.junit)
            dependencies {
                implementation(project())
                implementation(libs.truth)
                implementation(libs.ktor.client.okhttp)
                implementation(libs.kotlinx.serialization.json)
                implementation(libs.kotlinx.coroutines.core)
            }
            targets.all {
                testTask.configure {
                    environment("CODEBERG_LIVE_TOKEN", providers.environmentVariable("CODEBERG_LIVE_TOKEN").getOrElse(""))
                    // Set by hand, on one's own machine: CI never writes to this forge.
                    environment("CODEBERG_LIVE_WRITES", providers.environmentVariable("CODEBERG_LIVE_WRITES").getOrElse(""))
                    outputs.upToDateWhen { false }
                }
            }
        }
    }
}
