val lexiconSources = layout.projectDirectory.dir("lexicons")

fun lexiconFile(nsid: String): File = lexiconSources.file(nsid.replace('.', '/') + ".json").asFile

/** [calledMethods] and every lexicon they refer to (`ref`, `refs`), however deep. */
val neededLexicons: Set<String> = buildSet {
    val pending = ArrayDeque(calledMethods)
    val reference = Regex(""""refs?"\s*:\s*(\[[^\]]*]|"[^"]*")""")
    val quoted = Regex(""""([^"]+)"""")
    while (pending.isNotEmpty()) {
        val nsid = pending.removeFirst()
        if (!add(nsid)) continue
        val text = lexiconFile(nsid).takeIf { it.exists() }?.readText() ?: error("No lexicon for $nsid in lexicons/: run tools/specs/fetch.py")
        reference.findAll(text)
            .flatMap { quoted.findAll(it.groupValues[1]) }
            .map { it.groupValues[1].substringBefore('#') }
            .filter { it.isNotEmpty() }
            .forEach(pending::add)
    }
}

val preparedLexicons = layout.buildDirectory.dir("lexicons")

// ozone 0.3.4 writes a bound on an array's items as a bound on the array itself, which doesn't compile
// (org.tangled.git.defs#diffHunk): those bounds are dropped from the copy it reads. They only check what the server
// sends.
val prepareLexicons by tasks.registering {
    val sources = neededLexicons.associateWith(::lexiconFile)
    inputs.files(sources.values)
    outputs.dir(preparedLexicons)
    doLast {
        val out = preparedLexicons.get().asFile.apply {
            deleteRecursively()
            mkdirs()
        }
        sources.forEach { (nsid, file) ->
            val tree = JsonSlurper().parse(file)
            fun dropItemBounds(node: Any?) {
                when (node) {
                    is MutableMap<*, *> -> {
                        if (node["type"] == "array") {
                            (node["items"] as? MutableMap<*, *>)?.let { items ->
                                items.remove("minimum")
                                items.remove("maximum")
                            }
                        }
                        node.values.forEach(::dropItemBounds)
                    }
                    is List<*> -> node.forEach(::dropItemBounds)
                }
            }
            dropItemBounds(tree)
            out.resolve(nsid.replace('.', '/') + ".json").apply { parentFile.mkdirs() }.writeText(JsonOutput.toJson(tree))
        }
    }
}

