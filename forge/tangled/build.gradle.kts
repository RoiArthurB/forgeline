val lexiconSources = layout.projectDirectory.dir("lexicons")

fun lexiconFile(nsid: String): File = lexiconSources.file(nsid.replace('.', '/') + ".json").asFile

/** [calledMethods] and every lexicon they refer to (`ref`, `refs`), however deep. */
val neededLexicons: Set<String> = buildSet {
    val pending = ArrayDeque(calledMethods)
    val reference = Regex(""""refs?"\s*:\s*(\[[^\]]*]|"[^"]*")""")
    val quoted = Regex(""""([^"]+)"""")
    while (pending.isNotEmpty()) {
        val nsid = pending.removeFirst()
        if (!add(nsid)) continue
        val text = lexiconFile(nsid).takeIf { it.exists() }?.readText() ?: error("No lexicon for $nsid in lexicons/: run tools/specs/fetch.py")
        reference.findAll(text)
            .flatMap { quoted.findAll(it.groupValues[1]) }
            .map { it.groupValues[1].substringBefore('#') }
            .filter { it.isNotEmpty() }
            .forEach(pending::add)
    }
}

val preparedLexicons = layout.buildDirectory.dir("lexicons")

// Only the needed lexicons are handed to ozone.
val prepareLexicons = tasks.register<Sync>("prepareLexicons") {
    from(lexiconSources) { include(neededLexicons.map { it.replace('.', '/') + ".json" }) }
    into(preparedLexicons)
}

lexicons {
    namespace.set("fr.arthurbrugiere.forgeline.forge.tangled.xrpc")
    defaults {
        generateUnknownsForSealedTypes.set(true)
        generateUnknownsForEnums.set(true)
    }
    generateApi("TangledIndexApi") {
        packageName.set("fr.arthurbrugiere.forgeline.forge.tangled.xrpc")
        exclude("""com\.atproto\..*""")
        withKtorImplementation("TangledIndex")
        returnType.set(ApiReturnType.Response)
    }
    generateApi("AtprotoApi") {
        packageName.set("fr.arthurbrugiere.forgeline.forge.tangled.xrpc")
        exclude("""org\.tangled\..*""")
        withKtorImplementation("Atproto")
        returnType.set(ApiReturnType.Response)
    }
}

dependencies {
    lexicons(fileTree(preparedLexicons).builtBy(prepareLexicons))
}

