fun tangledHttpClient(engine: HttpClientEngine): HttpClient = forgeHttpClient(engine)

/**
 * Tangled's index (bobbin), which answers the AT Protocol queries (XRPC) the app reads: repositories, their git trees and
 * files, stars, profiles, Trending. Everything it serves is public: no call here needs an account.
 */
internal const val TANGLED_API = "https://api.tangled.org"

/** Where handles are turned into DIDs: Bluesky's public AppView, which resolves any AT Protocol handle, DNS or HTTPS. */
internal const val HANDLE_RESOLVER = "https://public.api.bsky.app"

/**
 * The XRPC clients the app talks to Tangled and the AT Protocol with. Their calls and the shapes of their answers are
 * generated by ozone (sh.christian.ozone) from the lexicons in `forge/tangled/lexicons`, which are Tangled's and the AT
 * Protocol's own: a field Tangled renames is a compile error after `tools/specs/fetch.py`, not a blank screen.
 *
 * Each XRPC host gets a client of its own on the app's HTTP engine (its connections and cache), with ozone's JSON
 * reading: Tangled's index, Bluesky's AppView for handles, and a person's own server (their PDS) for their records.
 */
class TangledXrpc(http: HttpClient) {
    private val engine = http.engine

    /** Tangled's index: repositories, their git, stars, follows, profiles, Trending. */
    internal val index = TangledIndex(on(TANGLED_API))

    /** Bluesky's AppView, which resolves any handle. */
    internal val handles = Atproto(on(HANDLE_RESOLVER))

    /** A person's own server at [base], as the one [token] signs in, if any. */
    internal fun server(base: String, token: String? = null): Atproto = Atproto(on(base, token))

    private fun on(base: String, token: String? = null): HttpClient = HttpClient(engine) {
        expectSuccess = false
        install(HttpTimeout)
        defaultRequest {
            url.takeFrom(base)
            header(HttpHeaders.UserAgent, USER_AGENT)
            header(HttpHeaders.Accept, "application/json")
            if (token != null) header(HttpHeaders.Authorization, "Bearer $token")
        }
    }
}

/**
 * An XRPC answer as the app reads them. XRPC answers a failure as 400 with `{"error": "RepoNotFound", "message": …}`: an
 * error named `…NotFound` is a 404 to the app, as any forge's missing repository or file is.
 */
internal inline fun <T : Any, R> AtpResponse<T>.toResult(read: (T) -> R): ForgeResult<R> = when (this) {
    is AtpResponse.Success -> ForgeResult.Success(read(response))
    is AtpResponse.Failure -> failure()
}

internal fun AtpResponse.Failure<*>.failure(): ForgeResult.Failure {
    val code = statusCode.code
    val name = error?.error
    val message = error?.message?.takeIf { it.isNotBlank() }
    return ForgeResult.Failure(
        when {
            code == HttpStatusCode.Unauthorized.value -> ForgeError.Unauthorized
            code == HttpStatusCode.TooManyRequests.value -> ForgeError.RateLimited(header("RateLimit-Reset")?.toLongOrNull())
            name?.endsWith("NotFound") == true -> ForgeError.Http(HttpStatusCode.NotFound.value, message ?: name)
            else -> ForgeError.Http(code, message ?: name)
        },
    )
}

/** A header of a failed answer, by its name in any case. */
private fun AtpResponse.Failure<*>.header(name: String): String? = headers.entries.firstOrNull { it.key.equals(name, ignoreCase = true) }?.value

/** A plain HTTP answer (a DID document, which isn't XRPC): its status alone tells a failure. */
internal suspend inline fun <T> HttpResponse.toResult(parse: HttpResponse.() -> T): ForgeResult<T> = when {
    status.isSuccess() -> ForgeResult.Success(parse())
    status == HttpStatusCode.Unauthorized -> ForgeResult.Failure(ForgeError.Unauthorized)
    else -> ForgeResult.Failure(ForgeError.Http(status.value, null))
}

/** [value] as a DID, or a 404 for a string that isn't one: nobody can be found by it. */
internal fun asDid(value: String): ForgeResult<Did> =
    runCatching { Did(value) }.fold({ ForgeResult.Success(it) }, { notFound("Not a DID: $value") })

/** [value] as a handle, or a 404 for one that can't be: no account goes by it. */
internal fun asHandle(value: String): ForgeResult<Handle> =
    runCatching { Handle(value) }.fold({ ForgeResult.Success(it) }, { notFound("Not a handle: $value") })

/** [this], then [next] with its value. */
internal inline fun <A, B> ForgeResult<A>.then(next: (A) -> ForgeResult<B>): ForgeResult<B> = when (this) {
    is ForgeResult.Failure -> this
    is ForgeResult.Success -> next(value)
}

/** AT Protocol times are RFC 3339, with `Z` or an offset. */
internal fun instant(value: String?): Instant? = value?.let { runCatching { OffsetDateTime.parse(it).toInstant() }.getOrNull() }

internal fun notFound(what: String): ForgeResult.Failure = ForgeResult.Failure(ForgeError.Http(HttpStatusCode.NotFound.value, what))
