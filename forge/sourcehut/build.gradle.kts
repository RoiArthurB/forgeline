plugins {
    alias(libs.plugins.forgeline.jvm.library)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.apollo)
}

// git.sr.ht and todo.sr.ht, through their GraphQL APIs, with a personal access token: see docs/SOURCEHUT.md.
dependencies {
    api(projects.forge.common)
    api(libs.ktor.client.core)
    implementation(libs.ktor.client.content.negotiation)
    implementation(libs.ktor.serialization.kotlinx.json)
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.kotlinx.coroutines.core)
    implementation(libs.apollo.api)

    testImplementation(libs.ktor.client.mock)
    testImplementation(libs.kotlinx.coroutines.test)
}

// The queries the app sends (src/main/graphql/*.graphql) are checked against git.sr.ht's schema (schema.graphqls,
// refreshed by tools/specs/fetch.py) and their answers' shapes generated by Apollo Kotlin. Only its models and JSON
// reading are used: the calls go through the app's own HTTP client (SourceHutHttp).
apollo {
    service("gitsrht") {
        packageName.set("fr.arthurbrugiere.forgeline.forge.sourcehut.graphql")
        // Times, cursors and addresses are read as the strings SourceHut writes them.
        mapScalarToKotlinString("Time")
        mapScalarToKotlinString("Cursor")
        mapScalarToKotlinString("URL")
    }
    // todo.sr.ht's tickets: a service of its own, with its own schema (refreshed by tools/specs/fetch.py too).
    service("todosrht") {
        srcDir("src/main/todo-graphql")
        packageName.set("fr.arthurbrugiere.forgeline.forge.sourcehut.todo")
        mapScalarToKotlinString("Time")
        mapScalarToKotlinString("Cursor")
        mapScalarToKotlinString("URL")
        mapScalarToKotlinString("Upload")
    }
}

// Contract tests against the real git.sr.ht, run nightly by .github/workflows/live.yml when SOURCEHUT_LIVE_TOKEN is set:
// SourceHut answers nothing without a token.
testing {
    suites {
        register<JvmTestSuite>("liveTest") {
            useJUnit(libs.versions.junit)
            dependencies {
                implementation(project())
                implementation(libs.truth)
                implementation(libs.ktor.client.okhttp)
                implementation(libs.kotlinx.coroutines.core)
            }
            targets.all {
                testTask.configure {
                    environment("SOURCEHUT_LIVE_TOKEN", providers.environmentVariable("SOURCEHUT_LIVE_TOKEN").getOrElse(""))
                    outputs.upToDateWhen { false }
                }
            }
        }
    }
}
