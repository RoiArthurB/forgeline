// The shapes of Bitbucket's answers are generated by OpenAPI Generator from Atlassian's own API description,
// spec/bitbucket.swagger.json (refreshed by tools/specs/fetch.py), into the `api` package: models only, the calls stay
// BitbucketHttp's. The description is made fit for generating first:
// - closed lists of values (a state, a merge strategy) are read as plain strings, as for Forgejo: a value Bitbucket
//   adds would otherwise make a whole answer unreadable;
// - nothing is required, and addresses, dates and ids are plain strings: Bitbucket leaves fields out of partial answers;
// - sizes are Longs: a repository's runs past 2 GB;
// - a field typed with a base type (an account, a pipeline's state) can hold any of its subtypes (a user, a team; a
//   completed state with its result), so the base is given each subtype's fields;
// - objects described inline get a model of their own instead of being read as raw JSON, links all the same one;
// - the fields Bitbucket answers with and its description leaves out are added, from spec/bitbucket.additions.json.
val preparedSpec = layout.buildDirectory.file("spec/bitbucket.json")

val prepareSpec by tasks.registering {
    // Only plain values are taken into the action, never the script's own: the configuration cache can't keep those.
    val source = layout.projectDirectory.file("spec/bitbucket.swagger.json")
    val additions = layout.projectDirectory.file("spec/bitbucket.additions.json")
    val target = preparedSpec
    inputs.file(source)
    inputs.file(additions)
    outputs.file(target)
    doLast {
        @Suppress("UNCHECKED_CAST")
        val tree = JsonSlurper().parse(source.asFile) as MutableMap<String, Any?>

        @Suppress("UNCHECKED_CAST")
        val definitions = tree["definitions"] as MutableMap<String, MutableMap<String, Any?>>

        fun loosen(node: Any?) {
            when (node) {
                is MutableMap<*, *> -> {
                    // Only where these are the keywords: a model can have a field named `required` too.
                    if (node["enum"] is List<*>) node.remove("enum")
                    if (node["required"] is List<*>) node.remove("required")
                    if (node["discriminator"] is String) node.remove("discriminator")
                    if (node["uniqueItems"] is Boolean) node.remove("uniqueItems")
                    // An object open to more fields would be generated as a map of them, which Kotlin can't extend.
                    if (node["additionalProperties"] is Boolean) node.remove("additionalProperties")
                    if (node["format"] in setOf("uri", "uuid", "date-time", "date", "email", "uri-reference")) node.remove("format")
                    node.values.forEach(::loosen)
                }
                is List<*> -> node.forEach(::loosen)
            }
        }
        loosen(definitions)

        // Sizes run past an Int: a repository of 3 GB (seen in Atlassian's workspace, 2026-11-18).
        fun widenSizes(node: Any?) {
            when (node) {
                is MutableMap<*, *> -> {
                    @Suppress("UNCHECKED_CAST")
                    val size = (node["properties"] as? Map<String, Any?>)?.get("size") as? MutableMap<String, Any?>
                    if (size?.get("type") == "integer") size["format"] = "int64"
                    node.values.forEach(::widenSizes)
                }
                is List<*> -> node.forEach(::widenSizes)
            }
        }
        widenSizes(definitions)

        @Suppress("UNCHECKED_CAST")
        fun parts(schema: Map<String, Any?>): List<MutableMap<String, Any?>> = (schema["allOf"] as? List<MutableMap<String, Any?>>).orEmpty()

        // The fields a schema declares itself, at its top or in its own part of an allOf.
        @Suppress("UNCHECKED_CAST")
        fun own(schema: MutableMap<String, Any?>): MutableMap<String, Any?> {
            (schema["properties"] as? MutableMap<String, Any?>)?.let { return it }
            parts(schema).firstOrNull { "properties" in it }?.let { return it["properties"] as MutableMap<String, Any?> }
            schema["type"] = "object"
            return LinkedHashMap<String, Any?>().also { schema["properties"] = it }
        }

        @Suppress("UNCHECKED_CAST")
        fun declared(schema: Map<String, Any?>): Map<String, Any?> =
            (schema["properties"] as? Map<String, Any?>).orEmpty() + parts(schema).flatMap { (it["properties"] as? Map<String, Any?>).orEmpty().entries }.associate { it.key to it.value }

        @Suppress("UNCHECKED_CAST")
        val added = JsonSlurper().parse(additions.asFile) as Map<String, Any?>
        added.filterKeys { !it.startsWith("_") }.forEach { (name, fields) ->
            val properties = own(definitions.getValue(name))
            (fields as Map<String, Any?>).forEach { (field, schema) -> properties.putIfAbsent(field, schema) }
        }

        fun bases(schema: Map<String, Any?>): List<String> =
            parts(schema).mapNotNull { (it["\$ref"] as? String)?.substringAfterLast('/') }.filter { it != "object" }

        var grew = true
        while (grew) {
            grew = false
            definitions.values.forEach { schema ->
                val fields = declared(schema)
                bases(schema).forEach { base ->
                    val properties = own(definitions.getValue(base))
                    fields.forEach { (field, value) -> if (field !in properties) { properties[field] = value; grew = true } }
                }
            }
        }
        definitions.values.forEach { schema ->
            if ("allOf" in schema) schema["allOf"] = parts(schema).filter { it["\$ref"] != "#/definitions/object" }
        }

        fun camel(text: String) = text.replace('-', '_').split('_').joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }

        @Suppress("UNCHECKED_CAST")
        fun hoist(name: String, schema: MutableMap<String, Any?>) {
            val holders = listOfNotNull(schema["properties"] as? MutableMap<String, Any?>) + parts(schema).mapNotNull { it["properties"] as? MutableMap<String, Any?> }
            holders.forEach { properties ->
                properties.entries.toList().forEach { (field, value) ->
                    val property = value as? MutableMap<String, Any?> ?: return@forEach
                    val items = property["items"] as? MutableMap<String, Any?>
                    val (holder, key, inline) = if (property["type"] == "array" && items != null) Triple(property, "items", items) else Triple(properties, field, property)
                    if (inline["title"] == "Link" && "link" in definitions) {
                        // Every link is the same object: one model for them all.
                        holder[key] = mapOf("\$ref" to "#/definitions/link")
                    } else if (inline["type"] == "object" && (inline["properties"] as? Map<*, *>)?.isNotEmpty() == true) {
                        val model = camel(name) + camel(field)
                        definitions[model] = inline
                        holder[key] = mapOf("\$ref" to "#/definitions/$model")
                        hoist(model, inline)
                    }
                }
            }
        }
        definitions.keys.toList().forEach { hoist(it, definitions.getValue(it)) }

        target.get().asFile.apply { parentFile.mkdirs() }.writeText(JsonOutput.toJson(tree))
    }
}

val generatedApi = layout.buildDirectory.dir("generated/openapi")

tasks.named<GenerateTask>("openApiGenerate") {
    dependsOn(prepareSpec)
    generatorName.set("kotlin")
    inputSpec.set(preparedSpec)
    outputDir.set(generatedApi)
    packageName.set("fr.arthurbrugiere.forgeline.forge.bitbucket.api")
    modelPackage.set("fr.arthurbrugiere.forgeline.forge.bitbucket.api")
    globalProperties.set(mapOf("models" to "", "modelDocs" to "false", "modelTests" to "false"))
    // Free-form JSON stays JSON.
    typeMappings.set(mapOf("AnyType" to "JsonElement", "object" to "JsonElement"))
    importMappings.set(mapOf("JsonElement" to "kotlinx.serialization.json.JsonElement"))
    configOptions.set(
        mapOf(
            "library" to "jvm-ktor",
            "serializationLibrary" to "kotlinx_serialization",
            "dateLibrary" to "string",
            "modelMutable" to "false",
            "sourceFolder" to "src/main/kotlin",
        ),
    )
}

kotlin.sourceSets.named("main") { kotlin.srcDir(generatedApi.map { it.dir("src/main/kotlin") }) }

tasks.named("compileKotlin") { dependsOn("openApiGenerate") }

// Contract tests against the real bitbucket.org, run nightly by .github/workflows/live.yml. The public ones read
// atlassian/atlassian-connect-express without an account. The signed-in ones need BITBUCKET_LIVE_EMAIL and
// BITBUCKET_LIVE_TOKEN (an Atlassian API token with Bitbucket's read scopes) and are skipped without them. The one that
// writes (BitbucketWriteLiveTest) also needs BITBUCKET_LIVE_WRITES=1 and BITBUCKET_LIVE_REPO, which no workflow sets:
// it is run by hand, on a scratch repository of one's own.
testing {
    suites {
        register<JvmTestSuite>("liveTest") {
            useJUnit(libs.versions.junit)
            dependencies {
                implementation(project())
                implementation(libs.truth)
                implementation(libs.ktor.client.okhttp)
                implementation(libs.kotlinx.serialization.json)
                implementation(libs.kotlinx.coroutines.core)
            }
            targets.all {
                testTask.configure {
                    listOf("BITBUCKET_LIVE_EMAIL", "BITBUCKET_LIVE_TOKEN", "BITBUCKET_LIVE_WRITES", "BITBUCKET_LIVE_REPO").forEach { name ->
                        environment(name, providers.environmentVariable(name).getOrElse(""))
                    }
                    outputs.upToDateWhen { false }
                }
            }
        }
    }
}
