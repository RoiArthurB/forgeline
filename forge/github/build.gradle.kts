// The GraphQL operations the app sends as they are (src/main/graphql/*.graphql) are checked against GitHub's schema
// (schema.graphqls, refreshed by tools/specs/fetch.py) and their answers' shapes generated by Apollo Kotlin; those put
// together at run time, one alias per repository asked at once, stay in Kotlin. Only Apollo's models and JSON reading
// are used: the calls go through the app's own HTTP client (GitHubRequests).
apollo {
    service("github") {
        packageName.set("fr.arthurbrugiere.forgeline.forge.github.graphql")
        // Times, addresses, HTML and object ids are read as the strings GitHub writes them.
        mapScalarToKotlinString("DateTime")
        mapScalarToKotlinString("URI")
        mapScalarToKotlinString("HTML")
        mapScalarToKotlinString("GitObjectID")
    }
}

// Contract tests against the real GitHub, run nightly by .github/workflows/live.yml.
// Authenticated checks need LIVE_TEST_PAT and are skipped without it.
testing {
    suites {
        register<JvmTestSuite>("liveTest") {
            useJUnit(libs.versions.junit)
            dependencies {
                implementation(project())
                implementation(libs.truth)
                implementation(libs.ktor.client.okhttp)
                implementation(libs.kotlinx.coroutines.core)
                implementation(libs.kotlinx.serialization.json)
            }
            targets.all {
                testTask.configure {
                    environment("LIVE_TEST_PAT", providers.environmentVariable("LIVE_TEST_PAT").getOrElse(""))
                    // Set by hand, on one's own machine: CI never writes to this forge.
                    environment("GITHUB_LIVE_WRITES", providers.environmentVariable("GITHUB_LIVE_WRITES").getOrElse(""))
                    outputs.upToDateWhen { false }
                }
            }
        }
    }
}
